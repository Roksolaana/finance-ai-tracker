"""Розмічений набір запитів для оцінки маршрутизації.

Кожен запит має:
  primary       — один найкращий шлях; за ним рахується строга точність;
  expected      — усі прийнятні шляхи; за ними — «мʼяка» точність. «Скільки
                  я витратила на каву» коректно відповідає і SQL за категорією
                  «кафе», і гібрид за змістом нотаток, але кращий — гібрид:
                  у «кафе» є ще й обіди;
  expected_args — аргументи, які мусить передати primary-інструмент
                  (частковий збіг, див. eval/scoring.py). Кортеж — кілька
                  рівноцінних значень, None — аргумент не має бути заданий.

Шляхи:
    sql      — query_transactions: суми, кількість, перелік за полями
    budgets  — check_budgets: витрати проти лімітів
    rag      — semantic_search_notes: пошук за змістом нотатки, без підсумку
    hybrid   — hybrid_search_and_sum: пошук за змістом + підсумок у базі
    none     — інструмент не потрібен

Дати в expected_args розраховано на «сьогодні» = TODAY. Прогін фіксує цю
дату і для промпту, і для інструментів (app.timeutils.frozen_today), тож
«минулий місяць» завжди означає вересень 2026.

Частина запитів навмисно розмовна, із суржиком і помилками в словах: так
питають у справжньому чаті, а не в анкеті.
"""

