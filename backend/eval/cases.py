"""Розмічений набір запитів для оцінки маршрутизації.

Кожен запит має очікуваний шлях обробки. Там, де коректних варіантів кілька,
перелічені всі: «скільки я витратила на каву» можна відповісти і через SQL за
категорією «кафе», і через гібрид за змістом нотаток — обидва дають правильну
суму, тож зараховуються обидва.

Позначки:
    sql     — детермінована агрегація за полями (сума, кількість, період)
    rag     — пошук за змістом нотатки, без підсумку
    hybrid  — пошук за змістом + підсумок у базі
    none    — інструмент не потрібен (поза темою, привітання, уточнення)
"""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class EvalCase:
    question: str
    expected: frozenset[str]
    # Навіщо цей запит у наборі — щоб у записці було видно покриття.
    rationale: str = ""


def case(question: str, *expected: str, why: str = "") -> EvalCase:
    return EvalCase(question=question, expected=frozenset(expected), rationale=why)


