THIS_MONTH_KEY = ("2026-10", None)


@dataclass(frozen=True)
class EvalCase:
    question: str
    primary: str
    also: frozenset[str] = frozenset()
    expected_args: dict[str, Any] = field(default_factory=dict)
    # Навіщо цей запит у наборі — щоб у записці було видно покриття.
    rationale: str = ""

    @property
    def expected(self) -> frozenset[str]:
        return self.also | {self.primary}


def case(question: str, primary: str, *also: str, args: dict | None = None, why: str = "") -> EvalCase:
    return EvalCase(question, primary, frozenset(also), args or {}, why)


