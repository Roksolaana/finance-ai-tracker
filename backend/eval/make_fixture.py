def _moment(rng: random.Random, day: datetime.date) -> str:
    return f"{day.isoformat()}T{rng.randint(8, 21):02d}:{rng.choice((0, 10, 20, 30, 40, 50)):02d}"


def build() -> dict:
    rng = random.Random(SEED)
    span = (TODAY - START).days
    rows = []

    def add(note: str, category: str, amount: int, when: str) -> None:
        sign = 1 if category == "дохід" else -1
        rows.append({"spent_at": when, "amount": sign * amount, "category": category, "note": note})

    for note, category, low, high, times in NOTES:
        pinned = PINNED.get(note, [])
        for index in range(times):
            day = pinned[index] if index < len(pinned) else START + datetime.timedelta(days=rng.randint(0, span))
            add(note, category, rng.randint(low, high), _moment(rng, day))
    for note, category, amount in PINNED_EXTRA:
        for day in PINNED[note]:
            add(note, category, amount, _moment(rng, day))
    for note, category, amount, day_of_month in MONTHLY:
        for month in range(START.month, TODAY.month + 1):
            add(note, category, amount, _moment(rng, datetime.date(2026, month, day_of_month)))

    rows.sort(key=lambda r: r["spent_at"])
    return {"today": TODAY.isoformat(), "timezone": "Europe/Kyiv", "transactions": rows, "budgets": BUDGETS}


def main() -> None:
    data = build()
    FIXTURE.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    notes = {r["note"] for r in data["transactions"]}
    print(f"{FIXTURE.name}: {len(data['transactions'])} транзакцій, {len(notes)} різних нотаток")


if __name__ == "__main__":
    main()
