"""Ембединги нотаток для семантичного пошуку.

Модель навмисно багатомовна. Англомовна `all-MiniLM-L6-v2` на українських
нотатках не розрізняє зміст: на запит «витрати через стрес і втому» вона
ставила «Флет вайт і круасан» (0.768) вище за «Заїла стрес перед дедлайном»
(0.709), бо всі оцінки збивались у вузький діапазон. Багатомовна модель на
тих самих даних дає 0.755 для правильної нотатки й обрив до 0.32 на
нерелевантних — саме цей розрив використовується як поріг релевантності.
"""

import logging
import threading
from pathlib import Path

logger = logging.getLogger(__name__)

MODEL_NAME = "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
EMBEDDING_DIM = 384

# Стала тека кешу: типова лежить у системному temp, який чиститься, і модель
# довелося б качати повторно.
CACHE_DIR = Path(__file__).resolve().parents[1] / ".model-cache"

# Нижче цього косинусного збігу вважаємо, що нотатка не стосується запиту.
#
# Відкалібровано на 10 розмічених запитах (6 з очікуваними відповідями, 4
# свідомо без них) по 492 реальних нотатках. Частка правильних рішень
# «знайти / промовчати»:
#   0.45 —  8/10   (пропускає «криптовалюта і акції» -> «АТБ» 0.485)
#   0.48 —  9/10
#   0.50 — 10/10   <- обрано
#   0.55 —  9/10   (втрачає слабші, але правильні збіги)
#
# Пробувалося також правило «перший результат має відірватися від наступного»
# замість порога — воно провалює найчастіший випадок, коли релевантних нотаток
# багато й оцінки близькі («кава»: 0.749 і 0.723), і відкидає геть усе.
RELEVANCE_THRESHOLD = 0.50

# Для запиту з одного слова поріг вищий. Коротке слово несе мало змісту, і
# його вектор лягає в «загальну» зону, близьку до будь-чого: на базі без
# жодної згадки стресу запит «стрес» давав «Varus» з оцінкою 0.605, тоді як
# повна фраза «витрати через стрес» — 0.348 і коректно відсікалась.
# 0.65 відкидає цей випадок, але лишає справжні однослівні збіги
# («навушники» -> «Купила навушники», 0.831).
SHORT_QUERY_THRESHOLD = 0.65
SHORT_QUERY_WORDS = 2

# Добавка до схожості, якщо слова із запиту прямо стоять у нотатці:
# оцінка = схожість + KEYWORD_BONUS × частка основ запиту, знайдених у нотатці
# (для «стрес чи втому» береться кращий із варіантів). Потрібна для довгих
# нотаток, де вектор тягне до головної теми: «Зайшла в магазин косметики,
# трохи щоб розвіятись і зняти стрес» має лише 0.27–0.29 на «стрес» і
# «витрати через стрес».
#
# Межі взято з 473 реальних нотаток:
#   нижня 0.234 — щоб «стрес» (0.266 + B) дотягнув до 0.50;
#   верхня 0.368 — щоб «Обід у кафе з друзями» (0.316 + B × 0.5, збіглось
#   лише «друзя» з двох основ) на «витрати на подарунки друзям» не пройшов.
# 0.30 — посередині. Оцінки для косметики: «витрати через стрес» 0.578,
# «…стрес чи втому» 0.585, «стрес» 0.566, «імпульсивні покупки через стрес»
# 0.631; «Обід у кафе з друзями» 0.466 (відсічено); «криптовалюта і акції»
# нічого не знаходить; «кава» — ті самі 8 нотаток, що й без бонусу.
# «Настільні ігри з друзями» (0.451 + 0.15 = 0.601) на запит про подарунки
# друзям усе ж проходить: щоб його відсікти, бонус мав би бути < 0.10, і
# тоді косметику не знайшов би жоден запит про стрес.
KEYWORD_BONUS = 0.30

_model = None
_lock = threading.Lock()


def get_model():
    """Вантажить модель при першому зверненні (≈0.22 ГБ, качається один раз)."""
    global _model
    if _model is None:
        with _lock:
            if _model is None:
                from fastembed import TextEmbedding

                logger.info("Завантаження моделі ембедингів %s", MODEL_NAME)
                _model = TextEmbedding(MODEL_NAME, cache_dir=str(CACHE_DIR))
    return _model


def embed(texts: list[str]) -> list[list[float]]:
    """Перетворює тексти на вектори. Порядок результатів відповідає вхідному."""
    if not texts:
        return []
    return [vector.tolist() for vector in get_model().embed(texts)]


def embed_one(text: str | None) -> list[float] | None:
    """Ембединг однієї нотатки. None, якщо тексту немає або модель недоступна."""
    if not text or not text.strip():
        return None
    try:
        return embed([text])[0]
    except Exception:
        # Семантичний пошук — не критична функція: транзакція має зберегтися
        # навіть якщо модель не завантажилась. Вектор дозаповнить backfill.
        logger.exception("Не вдалося порахувати ембединг нотатки")
        return None
